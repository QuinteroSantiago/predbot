#!/usr/bin/env python3
"""Regenerate internal/sports/teams_cfb.go: Poly US cfb slug code -> Kalshi
KXNCAAFGAME team code.

College football has ~260 teams and the venues' codes collide across teams
(Poly "sdst" is San Diego State; Kalshi "SDST" is South Dakota State), so a
hand-kept alias table like MLB/NFL's is not safe. Instead this pairs every open
game listed on both venues by date + team names ("Ball State vs. Kent State" on
Poly, "Ball St. vs Kent St." on Kalshi; away team first on both), and learns
the away/home code pairs from each confident match.

Existing entries are kept (teams roll off the open listings week to week), and a
code that would change meaning aborts the run instead of silently remapping.
A team missing from the table only means its games don't cross-list.

Usage: scripts/gen-cfb-teams.py && gofmt -w internal/sports/teams_cfb.go
"""
import collections, difflib, json, os, re, sys, urllib.request

OUT = os.path.join(os.path.dirname(__file__), "..", "internal", "sports", "teams_cfb.go")
H = {"User-Agent": "Mozilla/5.0", "Accept": "application/json"}  # Poly WAF rejects default UA
MONTHS = {m: i for i, m in enumerate("JAN FEB MAR APR MAY JUN JUL AUG SEP OCT NOV DEC".split(), 1)}


def get(url):
    return json.load(urllib.request.urlopen(urllib.request.Request(url, headers=H), timeout=30))


def poly_events():
    out, off = [], 0
    while True:
        ev = get(f"https://gateway.polymarket.us/v2/leagues/cfb/events?type=sport&limit=200&offset={off}").get("events", [])
        out += ev
        if len(ev) < 200:
            return out
        off += 200


def kalshi_events():
    out, cur = [], ""
    while True:
        d = get("https://api.elections.kalshi.com/trade-api/v2/events?series_ticker=KXNCAAFGAME"
                f"&status=open&with_nested_markets=true&limit=200&cursor={cur}")
        out += d["events"]
        cur = d.get("cursor", "")
        if not cur or not d["events"]:
            return out


def norm(name):
    s = name.lower().replace("st.", "state").replace("university at ", "u").replace("tennessee-", "ut ")
    s = re.sub(r"\(.*?\)", "", s.replace("-", " "))
    return re.sub(r"[^a-z0-9]", "", s)


def sides(title):
    return [x.strip() for x in re.split(r"\s+vs\.?\s+", title)]


def sim(a, b):
    return difflib.SequenceMatcher(None, norm(a), norm(b)).ratio()


def existing():
    if not os.path.exists(OUT):
        return {}
    return dict(re.findall(r'"([a-z0-9]+)":\s*"([A-Z0-9]+)"', open(OUT).read()))


def main():
    kby = collections.defaultdict(list)  # date -> [(away, home, awayCode, homeCode)]
    for e in kalshi_events():
        r = e["event_ticker"].split("-", 1)[1]
        date = f"20{r[:2]}-{MONTHS[r[2:5]]:02d}-{r[5:7]}"
        away, home = sides(e["title"])
        code = {m["yes_sub_title"]: m["ticker"].rsplit("-", 1)[1] for m in e["markets"]}
        if away in code and home in code:
            kby[date].append((away, home, code[away], code[home]))

    learned = collections.defaultdict(set)
    skipped = []
    for e in poly_events():
        parts = e["slug"].split("-")  # cfb-<away>-<home>-YYYY-MM-DD
        if len(parts) != 6:
            continue
        date = "-".join(parts[3:])
        away, home = sides(e["title"])
        scored = sorted((((sim(away, ka) + sim(home, kh)) / 2, ca, ch) for ka, kh, ca, ch in kby[date]), reverse=True)
        best = scored[0] if scored else (0, "", "")
        runner = scored[1][0] if len(scored) > 1 else 0
        if best[0] < 0.75 or best[0] - runner < 0.15:
            skipped.append(f"{e['slug']} ({e['title']})")
            continue
        learned[parts[1]].add(best[1])
        learned[parts[2]].add(best[2])

    table = existing()
    bad = []
    for code, ks in learned.items():
        if len(ks) > 1 or (code in table and table[code] not in ks):
            bad.append(f"{code}: {sorted(ks | ({table[code]} if code in table else set()))}")
        else:
            table[code] = ks.pop()
    if bad:
        sys.exit("conflicting Poly codes, fix by hand:\n  " + "\n  ".join(bad))

    with open(OUT, "w") as f:
        f.write("// Code generated by scripts/gen-cfb-teams.py; DO NOT EDIT.\n\n")
        f.write("package sports\n\n")
        f.write("// cfbPolyToKalshi maps a Poly US cfb slug team code to the Kalshi\n")
        f.write("// KXNCAAFGAME ticker suffix for the same school, which is the canonical code.\n")
        f.write("var cfbPolyToKalshi = map[string]string{\n")
        for code in sorted(table):
            f.write(f'\t"{code}": "{table[code]}",\n')
        f.write("}\n")
    print(f"{len(table)} teams ({len(learned)} seen this run); unmatched Poly games: {len(skipped)}", file=sys.stderr)
    for s in skipped:
        print("  " + s, file=sys.stderr)


if __name__ == "__main__":
    main()
